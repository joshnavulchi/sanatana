def translate_conversations(input_file, output_file):
    """Translate Telugu conversations to Hindi in the JSON file."""
    
    print(f"Reading {input_file}...")
    with open(input_file, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # Get the conversation array
    conversations = data['karma_philosophy']['script']['conversation']
    
    total = len(conversations)
    translated_count = 0
    
    print(f"\nTotal conversations: {total}")
    print("Translating conversations from Telugu to Hindi...")
    
    for i, conv in enumerate(conversations, 1):
        message = conv.get('message', '')
        
        # Check if this message needs translation
        if message in translations:
            conv['message'] = translations[message]
            translated_count += 1
